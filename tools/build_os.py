#!/usr/bin/env python3
"""Phase 4 OS image builder.

The OS is three assembly fragments with a FIXED physical layout
(the testbench loads one contiguous image at address 0, so the
fragments cannot be linked by address -- they are placed by
padding, and every cross-fragment address is a literal constant
documented in OS_BOOT.md):

  os_programs/firmware.s  at 0x0000, at most 0x1000 bytes
  os_programs/kernel_s.s  at 0x1000, at most 0x2000 bytes
  os_programs/user.s      at 0x3000, at most 0x1000 bytes

Two things tools/soc_asm.py cannot do, so this builder does them:
  - STRING lines: `label: STRING "text"` expands to the label plus
    .word lines holding the NUL-terminated string little-endian
    (only \\n and \\\\ escapes are supported). The base assembler
    has no string directive, so strings are data words, not a
    separate feature of the hardware.
  - Padding: .word 0 words fill each fragment up to its slot, so
    the kernel really starts at 0x1000 and the user at 0x3000.

Output (generated -- do not hand-edit):
  os_programs/os_boot.s   combined, expanded source (itself a
                          valid tools/soc_asm.py input)
  soc_hex/os_boot.hex     the image tools/os_check.py runs

Usage (from the big32 directory): python3 tools/build_os.py
Exits non-zero if any fragment overflows its slot: an overflow
would silently move the next fragment, so it is a hard error.
"""
import re
import sys

sys.path.insert(0, "tools")
import asm  # noqa: E402
import soc_asm  # noqa: E402

FRAGMENTS = [
    ("os_programs/firmware.s", 0x0000, 0x1000),
    ("os_programs/kernel_s.s", 0x1000, 0x2000),
    ("os_programs/user.s", 0x3000, 0x1000),
]

STR_RE = re.compile(r'^(\w+):\s*STRING\s+"((?:[^"\\]|\\.)*)"\s*$')


def expand_strings(text, src):
    out = []
    for lineno, raw in enumerate(text.splitlines(), 1):
        m = STR_RE.match(raw.strip())
        if not m:
            out.append(raw)
            continue
        label, body = m.group(1), m.group(2)
        data = bytearray()
        i = 0
        while i < len(body):
            c = body[i]
            if c == "\\":
                nxt = body[i + 1] if i + 1 < len(body) else ""
                if nxt == "n":
                    data.append(10)
                elif nxt == "\\":
                    data.append(92)
                else:
                    raise SystemExit(
                        f"{src}:{lineno}: unsupported escape \\{nxt}")
                i += 2
            else:
                data.append(ord(c))
                i += 1
        data.append(0)
        while len(data) % 4:
            data.append(0)
        out.append(f"{label}:")
        for off in range(0, len(data), 4):
            w = (data[off] | (data[off + 1] << 8) |
                 (data[off + 2] << 16) | (data[off + 3] << 24))
            out.append(f".word 0x{w:08x}")
    return "\n".join(out) + "\n"


def assemble(text):
    transformed, patches = soc_asm.transform(text)
    words = asm.assemble(transformed)
    for marker, real in patches:
        try:
            pos = words.index(marker)
        except ValueError:
            raise SystemExit(
                f"build_os: marker word {marker:08x} not found")
        words[pos] = real & 0xFFFFFFFF
    return words


def main():
    combined_src = ["# Generated by tools/build_os.py -- do not hand-edit.",
                    "# Fragments: os_programs/firmware.s, kernel_s.s, user.s.",
                    ""]
    combined_words = []
    for src, base, size in FRAGMENTS:
        expanded = expand_strings(open(src).read(), src)
        words = assemble(expanded)
        limit = size // 4
        if len(words) > limit:
            raise SystemExit(
                f"build_os: {src} is {len(words) * 4} bytes, "
                f"over its {size}-byte slot at 0x{base:x}")
        print(f"build_os: {src}: {len(words)} words "
              f"(slot 0x{base:x}..0x{base + size:x})")
        if combined_words and base // 4 != len(combined_words):
            raise SystemExit("build_os: layout gap (internal error)")
        combined_src.append(f"# ---- {src} at 0x{base:x} ----")
        combined_src.append(expanded)
        combined_words.extend(words)
        pad = limit - len(words)
        if pad:
            combined_src.append("\n".join(".word 0" for _ in range(pad)))
            combined_words.extend([0] * pad)
    with open("os_programs/os_boot.s", "w") as fh:
        fh.write("\n".join(combined_src) + "\n")
    # Re-assemble the combined source as a cross-check: it must
    # reproduce exactly the concatenated words.
    check = assemble("\n".join(combined_src) + "\n")
    if check != combined_words:
        raise SystemExit("build_os: combined re-assembly mismatch")
    with open("soc_hex/os_boot.hex", "w") as fh:
        for w in combined_words:
            fh.write(f"{w:08x}\n")
    print(f"build_os: {len(combined_words)} words -> soc_hex/os_boot.hex")


if __name__ == "__main__":
    main()
